@dataclass(frozen=True)
class ModelProfile:
    name: str
    # pathogen constants/defaults
    K_pathogen: np.ndarray
    k_rep: np.ndarray
    B0_rep: np.ndarray
    mu_rep: np.ndarray
    gamma_s_rep: np.ndarray
    rho_rep: np.ndarray
    eta_pathogen: np.ndarray
    alpha: np.ndarray
    beta: np.ndarray
    # probiotic constants
    probiotic_model: str  # 'two_compartment' or 'single'
    K_P: float
    k_P: float
    gamma_P: float
    rho_P: float
    eta_P: float
    mu_P: float
    P0: float
    # AMP/control/numerics
    lambda_amp: float
    u_max_rep: float
    T_thr_rep: np.ndarray
    dt_detect: float
    t_end: float
    dt: float


def _alpha_matrix() -> np.ndarray:
    a = np.full((N_STRAINS, N_STRAINS), 0.05, dtype=float)
    np.fill_diagonal(a, 1.0)
    return a


def od_to_cfu_ecoli(od600: float | np.ndarray) -> float | np.ndarray:
    """Convert E. coli OD600 to CFU/mL (R2 = 0.8460)."""
    return ECOLI_OD_TO_CFU_SLOPE * od600 + ECOLI_OD_TO_CFU_INTERCEPT


def od_to_cfu_llactis(od600: float | np.ndarray) -> float | np.ndarray:
    """Convert L. lactis OD600 to CFU/mL (R2 = 0.8673)."""
    return LLACTIS_OD_TO_CFU_SLOPE * od600 + LLACTIS_OD_TO_CFU_INTERCEPT


