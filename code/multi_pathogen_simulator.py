def _safe_r2(y_true: np.ndarray, y_pred: np.ndarray) -> float:
    yt = np.asarray(y_true, dtype=float).ravel()
    yp = np.asarray(y_pred, dtype=float).ravel()
    mask = np.isfinite(yt) & np.isfinite(yp)
    if int(mask.sum()) < 2 or float(np.var(yt[mask])) <= 1e-30:
        return float("nan")
    return float(r2_score(yt[mask], yp[mask]))


def _rmse(y_true: np.ndarray, y_pred: np.ndarray) -> float:
    yt = np.asarray(y_true, dtype=float).ravel()
    yp = np.asarray(y_pred, dtype=float).ravel()
    mask = np.isfinite(yt) & np.isfinite(yp)
    if int(mask.sum()) < 1:
        return float("nan")
    return float(np.sqrt(mean_squared_error(yt[mask], yp[mask])))


def _mean_target_wise_r2(y_true: np.ndarray, y_pred: np.ndarray) -> float:
    scores = [_safe_r2(y_true[:, j], y_pred[:, j]) for j in range(y_true.shape[1])]
    finite = [s for s in scores if np.isfinite(s)]
    return float(np.mean(finite)) if finite else float("nan")


