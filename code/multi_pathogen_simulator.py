def build_dcn_model(input_dim: int, output_dim: int, seed: int):
    try:
        import tensorflow as tf
        from tensorflow.keras import Input, Model
        from tensorflow.keras.layers import Dense, Dropout, concatenate, Layer, LayerNormalization, Activation
        from tensorflow.keras.optimizers import Adam
    except Exception as exc:
        raise ImportError(
            "TensorFlow is required for the DCN component. Install with: pip install tensorflow"
        ) from exc

    class CrossLayerV2(Layer):
        def __init__(self, rank=8, **kwargs):
            super().__init__(**kwargs)
            self.rank = rank

        def build(self, input_shape):
            dim = int(input_shape[0][-1])
            self.W = self.add_weight(name="W", shape=(dim, self.rank), initializer="glorot_uniform", trainable=True)
            self.v = self.add_weight(name="v", shape=(self.rank, 1), initializer="glorot_uniform", trainable=True)
            self.b = self.add_weight(name="b", shape=(dim,), initializer="zeros", trainable=True)
            self.ln = LayerNormalization()

        def call(self, inputs):
            x0, xl = inputs
            x_proj = tf.matmul(xl, self.W)
            x_proj = tf.matmul(x_proj, self.v)
            return self.ln(tf.multiply(x_proj, x0) + self.b + xl)

    tf.keras.backend.clear_session()
    tf.random.set_seed(int(seed))
    np.random.seed(int(seed))

    x0 = Input(shape=(input_dim,), name="features")
    xl = x0
    for _ in range(int(COMPARE_DCN_PARAMS["cross_layers"])):
        xl = CrossLayerV2(rank=int(COMPARE_DCN_PARAMS["cross_rank"]))([x0, xl])
    xd = x0
    for units in COMPARE_DCN_PARAMS["deep_units"]:
        xd = Dense(int(units))(xd)
        xd = LayerNormalization()(xd)
        xd = Activation("swish")(xd)
        xd = Dropout(float(COMPARE_DCN_PARAMS["dropout"]))(xd)
    merged = concatenate([xl, xd])
    out = Dense(output_dim, activation=None, name="output")(merged)
    model = Model(x0, out)
    model.compile(optimizer=Adam(float(COMPARE_DCN_PARAMS["learning_rate"])), loss="mse")
    return model


def train_dcn_with_inner_early_stopping(
    X_fit: np.ndarray,
    y_fit: np.ndarray,
    X_es: np.ndarray,
    y_es: np.ndarray,
    sample_weight_fit: Optional[np.ndarray],
    seed: int,
    max_epochs: Optional[int] = None,
) -> Tuple[Any, int]:
    """Fit DCN using an inner biological holdout for early stopping only."""
    from tensorflow.keras.callbacks import EarlyStopping, ReduceLROnPlateau

    epochs = int(max_epochs if max_epochs is not None else COMPARE_DCN_PARAMS["max_epochs"])
    model = build_dcn_model(X_fit.shape[1], y_fit.shape[1], seed=seed)
    callbacks = [
        EarlyStopping(
            "val_loss",
            patience=int(COMPARE_DCN_PARAMS["es_patience"]),
            restore_best_weights=True,
            verbose=0,
        ),
        ReduceLROnPlateau(
            "val_loss",
            factor=float(COMPARE_DCN_PARAMS["reduce_lr_factor"]),
            patience=int(COMPARE_DCN_PARAMS["reduce_lr_patience"]),
            verbose=0,
        ),
    ]
    history = model.fit(
        X_fit,
        y_fit,
        sample_weight=sample_weight_fit,
        validation_data=(X_es, y_es),
        epochs=epochs,
        batch_size=int(COMPARE_DCN_PARAMS["batch_size"]),
        callbacks=callbacks,
        verbose=0,
    )
    val_loss = np.asarray(history.history.get("val_loss", []), dtype=float)
    selected_epochs = int(np.argmin(val_loss) + 1) if val_loss.size else int(len(history.history.get("loss", [])))
    selected_epochs = max(1, selected_epochs)
    return model, selected_epochs


