@dataclass
class SimulationResult:
    profile_name: str
    times: np.ndarray
    B_total: np.ndarray
    B_S: np.ndarray
    B_T: np.ndarray
    P_total: np.ndarray
    P_S: Optional[np.ndarray]
    P_T: Optional[np.ndarray]
    C: np.ndarray
    dose_times: List[float]
    dose_count: int
    total_dosage: float
    P_AUC: float
    LR: np.ndarray
    u_max: float
    T_thr: np.ndarray


def _competition_term(alpha: np.ndarray, beta: np.ndarray, B_S: np.ndarray, B_T: np.ndarray, P_tot: float) -> np.ndarray:
    BT = B_S + B_T
    comp = alpha @ BT
    comp = comp + beta * P_tot
    return comp


def _simulate_forward_euler_core(
    B0: np.ndarray,
    k_arr: np.ndarray,
    gamma_arr: np.ndarray,
    gamma_T: np.ndarray,
    mu_arr: np.ndarray,
    u_max: float,
    T_thr: np.ndarray,
    K_pathogen: np.ndarray,
    eta_pathogen: np.ndarray,
    alpha: np.ndarray,
    beta: np.ndarray,
    two_compartment: bool,
    K_P: float,
    k_P: float,
    gamma_P: float,
    rho_P: float,
    eta_P: float,
    mu_P: float,
    P0: float,
    lambda_amp: float,
    dt_detect: float,
    t_end: float,
    dt: float,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, int, int]:
    """Pure-Python forward Euler integrator (fallback when Numba is unavailable)."""
    steps = int(round(t_end / dt)) + 1
    if steps < 2:
        steps = 2
    dt_sim = t_end / float(steps - 1)

    B_S = B0.copy()
    B_T = np.zeros(N_STRAINS, dtype=float)
    P_S = float(P0)
    P_T = 0.0
    P = float(P0)
    C = 0.0

    B_S_hist = np.zeros((steps, N_STRAINS), dtype=float)
    B_T_hist = np.zeros((steps, N_STRAINS), dtype=float)
    P_hist = np.zeros(steps, dtype=float)
    P_S_hist = np.zeros(steps, dtype=float)
    P_T_hist = np.zeros(steps, dtype=float)
    C_hist = np.zeros(steps, dtype=float)
    dose_times_buf = np.full(steps, np.nan, dtype=float)

    next_detect = 0.0
    dose_count = 0

    for idx in range(steps):
        t = idx * dt_sim
        B_S_hist[idx] = B_S
        B_T_hist[idx] = B_T
        if two_compartment:
            P_hist[idx] = P_S + P_T
            P_S_hist[idx] = P_S
            P_T_hist[idx] = P_T
        else:
            P_hist[idx] = P
        C_hist[idx] = C

        if t >= next_detect - 1e-12:
            if np.any(B_S + B_T > T_thr):
                C += u_max
                dose_count += 1
                dose_times_buf[dose_count - 1] = t
            next_detect += dt_detect

        P_tot = P_S + P_T if two_compartment else P
        comp = _competition_term(alpha, beta, B_S, B_T, P_tot)
        logistic_factor = 1.0 - comp / K_pathogen
        dB_S = k_arr * B_S * logistic_factor - gamma_arr * C * B_S - mu_arr * B_S
        dB_T = eta_pathogen * k_arr * B_T * logistic_factor - gamma_T * C * B_T + mu_arr * B_S
        dC = -lambda_amp * C

        B_S = np.clip(B_S + dB_S * dt_sim, 0.0, None)
        B_T = np.clip(B_T + dB_T * dt_sim, 0.0, None)

        if two_compartment:
            gamma_P_T = gamma_P * (1.0 - rho_P)
            P_tot = P_S + P_T
            dP_S = k_P * P_S * (1.0 - P_tot / K_P) - gamma_P * C * P_S - mu_P * P_S
            dP_T = eta_P * k_P * P_T * (1.0 - P_tot / K_P) - gamma_P_T * C * P_T + mu_P * P_S
            P_S = max(P_S + dP_S * dt_sim, 0.0)
            P_T = max(P_T + dP_T * dt_sim, 0.0)
        else:
            dP = k_P * P * (1.0 - P / K_P) - gamma_P * C * P
            P = max(P + dP * dt_sim, 0.0)

        C = max(C + dC * dt_sim, 0.0)

    return B_S_hist, B_T_hist, P_hist, P_S_hist, P_T_hist, C_hist, dose_times_buf, dose_count, steps


@njit(cache=True, fastmath=True)
def _simulate_forward_euler_numba(
    B0: np.ndarray,
    k_arr: np.ndarray,
    gamma_arr: np.ndarray,
    gamma_T: np.ndarray,
    mu_arr: np.ndarray,
    u_max: float,
    T_thr: np.ndarray,
    K_pathogen: np.ndarray,
    eta_pathogen: np.ndarray,
    alpha: np.ndarray,
    beta: np.ndarray,
    two_compartment: bool,
    K_P: float,
    k_P: float,
    gamma_P: float,
    rho_P: float,
    eta_P: float,
    mu_P: float,
    P0: float,
    lambda_amp: float,
    dt_detect: float,
    t_end: float,
    dt: float,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, int, int]:
    steps = int(round(t_end / dt)) + 1
    if steps < 2:
        steps = 2
    dt_sim = t_end / float(steps - 1)

    B_S = B0.copy()
    B_T = np.zeros(N_STRAINS)
    P_S = P0
    P_T = 0.0
    P = P0
    C = 0.0

    B_S_hist = np.zeros((steps, N_STRAINS))
    B_T_hist = np.zeros((steps, N_STRAINS))
    P_hist = np.zeros(steps)
    P_S_hist = np.zeros(steps)
    P_T_hist = np.zeros(steps)
    C_hist = np.zeros(steps)
    dose_times_buf = np.full(steps, np.nan)

    next_detect = 0.0
    dose_count = 0

    for idx in range(steps):
        t = idx * dt_sim
        for i in range(N_STRAINS):
            B_S_hist[idx, i] = B_S[i]
            B_T_hist[idx, i] = B_T[i]

        if two_compartment:
            P_hist[idx] = P_S + P_T
            P_S_hist[idx] = P_S
            P_T_hist[idx] = P_T
            P_tot = P_S + P_T
        else:
            P_hist[idx] = P
            P_tot = P
        C_hist[idx] = C

        if t >= next_detect - 1.0e-12:
            trigger = False
            for i in range(N_STRAINS):
                if B_S[i] + B_T[i] > T_thr[i]:
                    trigger = True
                    break
            if trigger:
                C += u_max
                dose_times_buf[dose_count] = t
                dose_count += 1
            next_detect += dt_detect

        comp = np.empty(N_STRAINS)
        BT = B_S + B_T
        for i in range(N_STRAINS):
            s = 0.0
            for j in range(N_STRAINS):
                s += alpha[i, j] * BT[j]
            comp[i] = s + beta[i] * P_tot

        for i in range(N_STRAINS):
            logistic_factor = 1.0 - comp[i] / K_pathogen[i]
            dB_S_i = k_arr[i] * B_S[i] * logistic_factor - gamma_arr[i] * C * B_S[i] - mu_arr[i] * B_S[i]
            dB_T_i = eta_pathogen[i] * k_arr[i] * B_T[i] * logistic_factor - gamma_T[i] * C * B_T[i] + mu_arr[i] * B_S[i]
            B_S[i] = max(B_S[i] + dB_S_i * dt_sim, 0.0)
            B_T[i] = max(B_T[i] + dB_T_i * dt_sim, 0.0)

        dC = -lambda_amp * C

        if two_compartment:
            gamma_P_T = gamma_P * (1.0 - rho_P)
            P_tot = P_S + P_T
            dP_S = k_P * P_S * (1.0 - P_tot / K_P) - gamma_P * C * P_S - mu_P * P_S
            dP_T = eta_P * k_P * P_T * (1.0 - P_tot / K_P) - gamma_P_T * C * P_T + mu_P * P_S
            P_S_new = P_S + dP_S * dt_sim
            P_T_new = P_T + dP_T * dt_sim
            if P_S_new < 0.0:
                P_S_new = 0.0
            if P_T_new < 0.0:
                P_T_new = 0.0
            P_S = P_S_new
            P_T = P_T_new
        else:
            dP = k_P * P * (1.0 - P / K_P) - gamma_P * C * P
            P_new = P + dP * dt_sim
            if P_new < 0.0:
                P_new = 0.0
            P = P_new

        C_new = C + dC * dt_sim
        if C_new < 0.0:
            C_new = 0.0
        C = C_new

    return B_S_hist, B_T_hist, P_hist, P_S_hist, P_T_hist, C_hist, dose_times_buf, dose_count, steps


def _run_forward_euler(
    B0: np.ndarray,
    k_arr: np.ndarray,
    gamma_arr: np.ndarray,
    gamma_T: np.ndarray,
    mu_arr: np.ndarray,
    u_max: float,
    T_thr: np.ndarray,
    profile: ModelProfile,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray, List[float], int, np.ndarray]:
    two_compartment = profile.probiotic_model == "two_compartment"
    euler_fn = _simulate_forward_euler_numba if NUMBA_SIMULATION_ENABLED else _simulate_forward_euler_core
    (
        B_S_hist,
        B_T_hist,
        P_hist,
        P_S_hist,
        P_T_hist,
        C_hist,
        dose_times_buf,
        dose_count,
        steps,
    ) = euler_fn(
        B0,
        k_arr,
        gamma_arr,
        gamma_T,
        mu_arr,
        u_max,
        T_thr,
        profile.K_pathogen,
        profile.eta_pathogen,
        profile.alpha,
        profile.beta,
        two_compartment,
        profile.K_P,
        profile.k_P,
        profile.gamma_P,
        profile.rho_P,
        profile.eta_P,
        profile.mu_P,
        profile.P0,
        profile.lambda_amp,
        profile.dt_detect,
        profile.t_end,
        profile.dt,
    )
    times = np.linspace(0.0, profile.t_end, steps)
    dose_times = [float(v) for v in dose_times_buf[:dose_count]]
    P_S_out = P_S_hist if two_compartment else None
    P_T_out = P_T_hist if two_compartment else None
    return B_S_hist, B_T_hist, P_hist, P_S_out, P_T_out, C_hist, dose_times, dose_count, times


def simulate_case(
    profile: ModelProfile,
    B0: Optional[np.ndarray] = None,
    k_arr: Optional[np.ndarray] = None,
    gamma_arr: Optional[np.ndarray] = None,
    rho_arr: Optional[np.ndarray] = None,
    mu_arr: Optional[np.ndarray] = None,
    u_max: Optional[float] = None,
    T_thr: Optional[np.ndarray] = None,
    return_history: bool = True,
) -> SimulationResult:
    """Forward Euler simulation of the five-pathogen threshold-triggered AMP system."""
    B0 = np.asarray(profile.B0_rep if B0 is None else B0, dtype=float)
    k_arr = np.asarray(profile.k_rep if k_arr is None else k_arr, dtype=float)
    gamma_arr = np.asarray(profile.gamma_s_rep if gamma_arr is None else gamma_arr, dtype=float)
    rho_arr = np.asarray(profile.rho_rep if rho_arr is None else rho_arr, dtype=float)
    mu_arr = np.asarray(profile.mu_rep if mu_arr is None else mu_arr, dtype=float)
    T_thr = np.asarray(profile.T_thr_rep if T_thr is None else T_thr, dtype=float)
    u_max = float(profile.u_max_rep if u_max is None else u_max)

    if not (len(B0) == len(k_arr) == len(gamma_arr) == len(rho_arr) == len(mu_arr) == len(T_thr) == N_STRAINS):
        raise ValueError("B0, k_arr, gamma_arr, rho_arr, mu_arr, and T_thr must all have length 5.")
    if np.any(T_thr <= 0) or u_max < 0:
        raise ValueError("Thresholds must be positive and u_max must be non-negative.")

    # gamma_T = gamma_S * (1-rho); default rho=0.5 gives gamma_T = 0.5 gamma_S.
    gamma_T = gamma_arr * (1.0 - rho_arr)

    (
        B_S_hist,
        B_T_hist,
        P_hist,
        P_S_hist,
        P_T_hist,
        C_hist,
        dose_times,
        dose_count,
        times,
    ) = _run_forward_euler(B0, k_arr, gamma_arr, gamma_T, mu_arr, u_max, T_thr, profile)

    B_total = B_S_hist + B_T_hist
    P_AUC = float(np.trapezoid(P_hist / profile.K_P, times) / profile.t_end)
    LR = np.log10(B0 / np.clip(B_total[-1], 1.0, None))

    return SimulationResult(
        profile_name=profile.name,
        times=times,
        B_total=B_total,
        B_S=B_S_hist,
        B_T=B_T_hist,
        P_total=P_hist,
        P_S=P_S_hist,
        P_T=P_T_hist,
        C=C_hist,
        dose_times=dose_times,
        dose_count=dose_count,
        total_dosage=float(dose_count * u_max),
        P_AUC=P_AUC,
        LR=LR,
        u_max=u_max,
        T_thr=T_thr,
    )


