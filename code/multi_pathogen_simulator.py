def main() -> None:
    parser = argparse.ArgumentParser(description="Review-ready wound control simulation and ML pipeline")
    parser.add_argument(
        "--mode",
        choices=["representative", "generate_dataset", "train_compare", "mu_sensitivity"],
        default="representative",
    )
    parser.add_argument(
        "--profile",
        default="paper_figure",
        choices=list(PROFILE_ALIASES),
        help="ODE parameter profile (default: paper_figure).",
    )
    parser.add_argument("--outdir", default=".")
    parser.add_argument(
        "--n_bio",
        type=int,
        default=500,
        help=(
            "Legacy helper: 500 gives the 220,000-row LHS grid in this module. "
            "The formal 352,000-row manuscript workflow is generated by microbio_dataset.py."
        ),
    )
    parser.add_argument("--x_csv", default="X_features.csv")
    parser.add_argument("--y_csv", default="y_targets.csv")
    parser.add_argument(
        "--metadata_csv",
        default=os.path.join("data", "microbio_formal_dataset", "sample_metadata.csv"),
        help="sample_metadata.csv with bio_id (required for train_compare).",
    )
    parser.add_argument(
        "--sample_weight_csv",
        default=os.path.join("data", "microbio_formal_dataset", "sample_weights.csv"),
        help="sample_weights.csv (required for train_compare).",
    )
    parser.add_argument(
        "--tar_predictions_dir",
        default=os.path.join("results", "tree_srl_benchmark", "repeats"),
        help="Directory of saved TAR repeat_XXX/predictions.csv folders.",
    )
    parser.add_argument("--n_repeats", type=int, default=100, help="Reuse the first n_repeats saved TAR outer splits.")
    parser.add_argument("--seed", type=int, default=42, help="Base seed for inner splits (outer seeds come from TAR files).")
    parser.add_argument(
        "--include_tabnet",
        action=argparse.BooleanOptionalAction,
        default=True,
        help="Include TabNet (task-matched reimplementation).",
    )
    parser.add_argument(
        "--device",
        default="cpu",
        choices=["cpu", "gpu", "cuda"],
        help="Device for LightGBM residual / TabNet (DCN uses TensorFlow default device).",
    )
    parser.add_argument(
        "--baseline",
        default="XGBoost",
        choices=["GBDT", "XGBoost"],
        help="Deprecated for train_compare; retained for CLI compatibility.",
    )
    parser.add_argument(
        "--sample_index",
        type=int,
        default=0,
        help="Deprecated for train_compare; retained for CLI compatibility.",
    )
    parser.add_argument(
        "--morris_plot_only",
        action="store_true",
        help="For --mode mu_sensitivity: rebuild figure/CSV from saved Morris indices only (no re-analysis).",
    )
    args = parser.parse_args()
    os.makedirs(args.outdir, exist_ok=True)

    profile = get_profile(args.profile)

    if args.mode == "representative":
        res = simulate_case(profile)
        save_representative_artifacts(res, profile, args.outdir)
        print(f"profile={profile.name}, P_AUC={res.P_AUC:.6g}, LR={np.round(res.LR, 4)}, doses={res.dose_count}, total_dosage={res.total_dosage:.1f} ug/mL")

    elif args.mode == "generate_dataset":
        df = generate_rows(profile, n_bio=args.n_bio)
        wound_path = os.path.join(args.outdir, "WOUND.csv")
        df.to_csv(wound_path, index=False)
        save_dataset_artifacts(df, profile, args.outdir, n_bio=args.n_bio)
        print(f"Saved {wound_path}")
        print(f"Dataset shape: {df.shape}")

    elif args.mode == "train_compare":
        train_compare(
            profile,
            x_csv=args.x_csv,
            y_csv=args.y_csv,
            outdir=args.outdir,
            metadata_csv=args.metadata_csv,
            sample_weight_csv=args.sample_weight_csv,
            tar_predictions_dir=args.tar_predictions_dir,
            n_repeats=args.n_repeats,
            seed=args.seed,
            include_tabnet=bool(args.include_tabnet),
            device=args.device,
            baseline=args.baseline,
            sample_index=args.sample_index,
        )

    elif args.mode == "mu_sensitivity":
        run_mu_sensitivity(profile, args.outdir, plot_only=args.morris_plot_only)


if __name__ == "__main__":
    main()
