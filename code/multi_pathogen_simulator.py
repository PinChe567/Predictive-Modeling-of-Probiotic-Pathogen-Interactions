def y_to_controller(y_pred: np.ndarray, columns: Optional[List[str]] = None) -> Tuple[float, np.ndarray]:
    """Return (u_max, T_thr[5]) from either column-labeled or original-order predictions."""
    arr = np.asarray(y_pred, dtype=float).reshape(-1)
    if len(arr) != 6:
        raise ValueError("Expected six control targets.")
    if columns is not None and set(TARGET_COLS).issubset(set(columns)):
        series = pd.Series(arr, index=columns)
        u = float(series["u_max"])
        T = series[[f"Tthr_{i}" for i in range(1, 6)]].values.astype(float)
    else:
        # Original uploaded-code order.
        u = float(arr[0])
        T = arr[1:6].astype(float)
    return float(np.clip(u, 0.0, None)), np.clip(T, 1.0, None)


