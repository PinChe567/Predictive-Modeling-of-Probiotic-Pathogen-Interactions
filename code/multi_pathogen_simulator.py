def _assert_no_outer_val_leakage(
    context: str,
    used_indices: Sequence[int],
    outer_val_indices: Sequence[int],
) -> None:
    used = np.asarray(used_indices, dtype=int).ravel()
    forbidden = np.asarray(outer_val_indices, dtype=int).ravel()
    if used.size == 0:
        return
    overlap = np.intersect1d(used, forbidden)
    if overlap.size:
        raise AssertionError(
            f"Leakage detected in {context}: {overlap.size} outer-validation indices "
            f"were used for fitting/scaling/early-stopping/residual training "
            f"(first overlaps={overlap[:10].tolist()})."
        )


