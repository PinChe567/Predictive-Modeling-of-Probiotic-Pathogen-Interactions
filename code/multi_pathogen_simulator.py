def y_to_controller(y_pred: np.ndarray, columns: Optional[List[str]] = None) -> Tuple[float, np.ndarray]:
    """Return (u_max, T_thr[5]) from either column-labeled or original-order predictions."""
    arr = np.asarray(y_pred, dtype=float).reshape(-1)
    if len(arr) != 6:
        raise ValueError("Expected six control targets.")
    if columns is not None and set(TARGET_COLS).issubset(set(columns)):
        series = pd.Series(arr, index=columns)
        u = float(series["u_max"])
        T = series[[f"Tthr_{i}" for i in range(1, 6)]].values.astype(float)
    else:
        # Original uploaded-code order.
        u = float(arr[0])
        T = arr[1:6].astype(float)
    return float(np.clip(u, 0.0, None)), np.clip(T, 1.0, None)


def train_dcn(X_train, y_train_log, X_val, y_val_log, epochs: int = 250, batch_size: int = 256):
    try:
        import tensorflow as tf
        from tensorflow.keras import Input, Model
        from tensorflow.keras.layers import Dense, Dropout, concatenate, Layer, LayerNormalization, Activation
        from tensorflow.keras.optimizers import Adam
        from tensorflow.keras.callbacks import EarlyStopping, ReduceLROnPlateau
    except Exception as exc:
        raise ImportError(
            "TensorFlow is required for the DCN component of the manuscript SRL model. "
            "Install it with: pip install tensorflow"
        ) from exc

    class CrossLayerV2(Layer):
        def __init__(self, rank=8, **kwargs):
            super().__init__(**kwargs)
            self.rank = rank

        def build(self, input_shape):
            dim = int(input_shape[0][-1])
            self.W = self.add_weight(name="W", shape=(dim, self.rank), initializer="glorot_uniform", trainable=True)
            self.v = self.add_weight(name="v", shape=(self.rank, 1), initializer="glorot_uniform", trainable=True)
            self.b = self.add_weight(name="b", shape=(dim,), initializer="zeros", trainable=True)
            self.ln = LayerNormalization()

        def call(self, inputs):
            x0, xl = inputs
            x_proj = tf.matmul(xl, self.W)
            x_proj = tf.matmul(x_proj, self.v)
            return self.ln(tf.multiply(x_proj, x0) + self.b + xl)

    def build_dcn(input_dim, output_dim):
        x0 = Input(shape=(input_dim,), name="features")
        xl = x0
        for _ in range(5):
            xl = CrossLayerV2(rank=8)([x0, xl])
        xd = x0
        for units in (128, 64):
            xd = Dense(units)(xd)
            xd = LayerNormalization()(xd)
            xd = Activation("swish")(xd)
            xd = Dropout(0.2)(xd)
        merged = concatenate([xl, xd])
        out = Dense(output_dim, activation=None, name="output")(merged)
        return Model(x0, out)

    tf.random.set_seed(42)
    model = build_dcn(X_train.shape[1], y_train_log.shape[1])
    model.compile(optimizer=Adam(1e-3), loss="mse")
    model.fit(
        X_train,
        y_train_log,
        validation_data=(X_val, y_val_log),
        epochs=epochs,
        batch_size=batch_size,
        callbacks=[
            EarlyStopping("val_loss", patience=20, restore_best_weights=True, verbose=1),
            ReduceLROnPlateau("val_loss", factor=0.5, patience=10, verbose=1),
        ],
        verbose=0,
    )
    return model


def train_compare(profile: ModelProfile, x_csv: str, y_csv: str, baseline: str, sample_index: int, outdir: str) -> None:
    try:
        from xgboost import XGBRegressor
        from lightgbm import LGBMRegressor
    except Exception as exc:
        raise ImportError("xgboost and lightgbm are required: pip install xgboost lightgbm") from exc

    X_df = pd.read_csv(x_csv).dropna()
    y_df = pd.read_csv(y_csv).loc[X_df.index].dropna()
    X_df = X_df.loc[y_df.index]
    if set(TARGET_COLS).issubset(y_df.columns):
        y_df = y_df[TARGET_COLS]
    if y_df.shape[1] != 6:
        raise ValueError("y_targets.csv must have six columns: u_max and Tthr_1..Tthr_5.")

    X = X_df.values
    y = y_df.values
    y_log = np.log1p(np.clip(y, 0.0, None))

    X_train_raw, X_val_raw, y_train_log, y_val_log, y_train, y_val = train_test_split(
        X, y_log, y, test_size=0.15, random_state=42
    )

    scaler = StandardScaler().fit(X_train_raw)
    X_train = scaler.transform(X_train_raw)
    X_val = scaler.transform(X_val_raw)

    baseline = baseline.upper()
    if baseline == "GBDT":
        baseline_model = MultiOutputRegressor(GradientBoostingRegressor(n_estimators=100, random_state=42))
        baseline_model.fit(X_train, y_train_log)
        pred_base_log = baseline_model.predict(X_val)
        baseline_name = "GBDT"
    elif baseline == "XGBOOST":
        xgb_base = XGBRegressor(
            objective="reg:squarederror",
            n_estimators=300,
            learning_rate=0.05,
            max_depth=6,
            subsample=0.8,
            colsample_bytree=0.8,
            eval_metric="rmse",
            random_state=42,
            n_jobs=-1,
        )
        baseline_model = MultiOutputRegressor(xgb_base)
        baseline_model.fit(X_train, y_train_log)
        pred_base_log = baseline_model.predict(X_val)
        baseline_name = "XGBoost"
    else:
        raise ValueError("baseline must be 'GBDT' or 'XGBoost'.")

    # XGBoost base learner for SRL.
    xgb_models = []
    for i in range(y_train_log.shape[1]):
        model = XGBRegressor(
            objective="reg:squarederror",
            n_estimators=300,
            learning_rate=0.05,
            max_depth=6,
            subsample=0.8,
            colsample_bytree=0.8,
            eval_metric="rmse",
            random_state=42,
            n_jobs=-1,
        )
        model.fit(X_train, y_train_log[:, i])
        xgb_models.append(model)
    pred_train_xgb = np.column_stack([m.predict(X_train) for m in xgb_models])
    pred_val_xgb = np.column_stack([m.predict(X_val) for m in xgb_models])

    # DCN base learner for SRL.
    dcn = train_dcn(X_train, y_train_log, X_val, y_val_log)
    pred_train_dcn = dcn.predict(X_train, verbose=0)
    pred_val_dcn = dcn.predict(X_val, verbose=0)

    # Stacked residual logic in log target space.
    init_train = 0.5 * (pred_train_dcn + pred_train_xgb)
    init_val = 0.5 * (pred_val_dcn + pred_val_xgb)
    resid_train = y_train_log - init_train
    meta_train = np.hstack([pred_train_dcn, pred_train_xgb])
    meta_val = np.hstack([pred_val_dcn, pred_val_xgb])

    res_base = LGBMRegressor(
        n_estimators=500,
        learning_rate=0.05,
        max_depth=4,
        subsample=0.8,
        colsample_bytree=0.8,
        random_state=42,
        n_jobs=-1,
        verbosity=-1,
        device_type="gpu",
    )
    res_model = MultiOutputRegressor(res_base)
    try:
        res_model.fit(meta_train, resid_train)
    except Exception as exc:
        import warnings

        warnings.warn(f"LightGBM GPU fit failed ({exc}); retrying on CPU.", stacklevel=2)
        res_base.set_params(device_type="cpu")
        res_model = MultiOutputRegressor(res_base)
        res_model.fit(meta_train, resid_train)
    resid_pred_val = res_model.predict(meta_val)
    final_pred_log = init_val + resid_pred_val

    true_val = np.expm1(y_val_log)
    pred_srl = np.expm1(final_pred_log)
    pred_base = np.expm1(pred_base_log)

    r2_srl_each = [r2_score(true_val[:, i], pred_srl[:, i]) for i in range(true_val.shape[1])]
    r2_base_each = [r2_score(true_val[:, i], pred_base[:, i]) for i in range(true_val.shape[1])]
    r2_df = pd.DataFrame({"target": list(y_df.columns), "SRL_R2": r2_srl_each, f"{baseline_name}_R2": r2_base_each})
    r2_df.loc[len(r2_df)] = ["mean", float(np.mean(r2_srl_each)), float(np.mean(r2_base_each))]
    r2_df.to_csv(os.path.join(outdir, "model_r2_summary.csv"), index=False)

    idx = int(sample_index)
    if idx < 0 or idx >= X_val_raw.shape[0]:
        raise IndexError("sample_index out of range for validation set.")
    bio = X_val_raw[idx, :25]
    B0 = bio[0:5]
    k_arr = bio[5:10]
    gamma_arr = bio[10:15]
    rho_arr = bio[15:20]
    mu_arr = bio[20:25]

    u_srl, T_srl = y_to_controller(pred_srl[idx], list(y_df.columns))
    u_base, T_base = y_to_controller(pred_base[idx], list(y_df.columns))
    res_srl = simulate_case(profile, B0, k_arr, gamma_arr, rho_arr, mu_arr, u_srl, T_srl)
    res_baseline = simulate_case(profile, B0, k_arr, gamma_arr, rho_arr, mu_arr, u_base, T_base)

    save_train_compare_trajectory_artifact(res_srl, outdir)
    pd.concat([metrics_dataframe("SRL", res_srl), metrics_dataframe(baseline_name, res_baseline)], ignore_index=True).to_csv(
        os.path.join(outdir, "reviewer_closed_loop_metrics.csv"), index=False
    )

    print("Saved model_r2_summary.csv")
    print("Saved reviewer_closed_loop_metrics.csv")


