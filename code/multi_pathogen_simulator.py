@dataclass
class LegacySimulationResult:
    times: np.ndarray
    B_total: np.ndarray
    B_S: np.ndarray
    B_R: np.ndarray
    P_S: np.ndarray
    P_R: np.ndarray
    C: np.ndarray
    dose_times: List[float]
    dose_count: int
    total_dosage: float
    P_AUC: float
    LR: np.ndarray
    LR_final: np.ndarray
    LR_terminal_median: np.ndarray
    LR_terminal_mean: np.ndarray
    pathogen_AUC: np.ndarray
    LR_auc: np.ndarray
    final_total_pathogen: float
    final_probiotic: float


def _legacy_metrics_from_trajectory(
    B0: np.ndarray,
    times: np.ndarray,
    B_total: np.ndarray,
    P_total: np.ndarray,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    t_end = float(times[-1])
    terminal_mask = times >= (t_end - 12.0) - 1e-12
    B_terminal = B_total[terminal_mask]
    LR_final = np.log10(B0 / np.clip(B_total[-1], 1.0, None))
    LR_terminal_median = np.log10(B0 / np.clip(np.median(B_terminal, axis=0), 1.0, None))
    LR_terminal_mean = np.log10(B0 / np.clip(np.mean(B_terminal, axis=0), 1.0, None))
    pathogen_AUC = np.trapezoid(B_total, times, axis=0) / t_end
    LR_auc = np.log10(B0 / np.clip(pathogen_AUC, 1.0, None))
    return LR_final, LR_terminal_median, LR_terminal_mean, pathogen_AUC, LR_auc


def simulate_paper_case(
    B0: np.ndarray = B0_S_REP,
    k_arr: np.ndarray = K_REP,
    gamma_arr: np.ndarray = GAMMA_S_REP,
    rho_arr: np.ndarray = RHO_REP,
    mu_arr: np.ndarray = MU_REP,
    u_max: float = PAPER_FIGURE_PROFILE.u_max_rep,
    T_thr: np.ndarray = PAPER_FIGURE_PROFILE.T_thr_rep,
) -> LegacySimulationResult:
    """Legacy positional API for dataset generation and closed-loop evaluation."""
    raw = simulate_case(
        PAPER_FIGURE_PROFILE,
        B0,
        k_arr,
        gamma_arr,
        rho_arr,
        mu_arr,
        u_max,
        T_thr,
        return_history=True,
    )
    P_total = raw.P_total
    P_S = raw.P_S if raw.P_S is not None else np.zeros_like(P_total)
    P_R = raw.P_T if raw.P_T is not None else np.zeros_like(P_total)
    LR_final, LR_terminal_median, LR_terminal_mean, pathogen_AUC, LR_auc = _legacy_metrics_from_trajectory(
        np.asarray(B0, dtype=float),
        raw.times,
        raw.B_total,
        P_total,
    )
    return LegacySimulationResult(
        times=raw.times,
        B_total=raw.B_total,
        B_S=raw.B_S,
        B_R=raw.B_T,
        P_S=P_S,
        P_R=P_R,
        C=raw.C,
        dose_times=list(raw.dose_times),
        dose_count=int(raw.dose_count),
        total_dosage=float(raw.total_dosage),
        P_AUC=float(raw.P_AUC),
        LR=LR_terminal_median.copy(),
        LR_final=LR_final,
        LR_terminal_median=LR_terminal_median,
        LR_terminal_mean=LR_terminal_mean,
        pathogen_AUC=pathogen_AUC,
        LR_auc=LR_auc,
        final_total_pathogen=float(raw.B_total[-1].sum()),
        final_probiotic=float(P_total[-1]),
    )


def simulation_outcome_row(res: LegacySimulationResult) -> List[float]:
    return [
        res.dose_count,
        res.total_dosage,
        res.final_total_pathogen,
        res.final_probiotic,
        float(np.mean(res.LR_final)),
        float(np.min(res.LR_final)),
        *res.LR_final.tolist(),
        *res.LR_terminal_median.tolist(),
        *res.LR_terminal_mean.tolist(),
        *res.pathogen_AUC.tolist(),
        *res.LR_auc.tolist(),
    ]


def row_from_case(B0, k_arr, gamma_arr, rho_arr, mu_arr, u_max, T_thr) -> np.ndarray:
    res = simulate_paper_case(B0, k_arr, gamma_arr, rho_arr, mu_arr, u_max, T_thr)
    return np.concatenate(
        [B0, k_arr, gamma_arr, rho_arr, mu_arr, [u_max], T_thr, [res.P_AUC], res.LR, simulation_outcome_row(res)]
    )


