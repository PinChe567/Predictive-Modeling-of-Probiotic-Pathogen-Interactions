def generate_rows(profile: ModelProfile, n_bio: int = 500) -> pd.DataFrame:
    """Generate 220,000 rows when n_bio=500 under the original code-aligned grid."""
    if qmc is None:
        raise ImportError("scipy is required: pip install scipy")

    sampler = qmc.LatinHypercube(d=15, seed=0)
    lhs_mat = sampler.random(n=n_bio)

    def scale(v, lo, hi):
        return lo + v * (hi - lo)

    B0_lo, B0_hi = 0.6 * profile.B0_rep, 1.4 * profile.B0_rep
    k_lo, k_hi = 0.8 * profile.k_rep, 1.2 * profile.k_rep
    g_lo, g_hi = 0.8 * profile.gamma_s_rep, 1.2 * profile.gamma_s_rep
    rho_add_values = [0.0, 0.05]
    u_grid = np.arange(10.0, 31.0, 2.0)
    thr_levels = 0.4 * 2.0e7 * 1.26 ** np.arange(10)

    bio_vecs = []
    for row in lhs_mat:
        ptr = 0
        B0 = scale(row[ptr:ptr + 5], B0_lo, B0_hi); ptr += 5
        k_v = scale(row[ptr:ptr + 5], k_lo, k_hi); ptr += 5
        g_v = scale(row[ptr:ptr + 5], g_lo, g_hi); ptr += 5
        bio_vecs.append((B0, k_v, g_v))

    sob = qmc.Sobol(d=5, scramble=True, seed=42)
    T_unit = sob.random_base2(m=4)[:10]
    T_vecs = thr_levels[(T_unit * 10).astype(int)]

    rows = []
    mu_designs = [0.8 * profile.mu_rep, 1.2 * profile.mu_rep]
    total = len(bio_vecs) * len(mu_designs) * len(rho_add_values) * len(u_grid) * len(T_vecs)

    done = 0
    for B0, k_v, g_v in bio_vecs:
        for mu_v, radd in itertools.product(mu_designs, rho_add_values):
            rho_v = np.clip(profile.rho_rep + radd, 0.0, 0.95)
            for u in u_grid:
                for T in T_vecs:
                    rows.append(_row_from_profile_case(profile, B0, k_v, g_v, rho_v, mu_v, float(u), T))
                    done += 1
                    if done % 10000 == 0:
                        print(f"generated {done:,}/{total:,} rows")

    return pd.DataFrame(rows, columns=ALL_COLS)


