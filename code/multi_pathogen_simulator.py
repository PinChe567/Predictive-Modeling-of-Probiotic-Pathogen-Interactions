def train_lgbm_residual(
    meta_train: np.ndarray,
    resid_train: np.ndarray,
    sample_weight: Optional[np.ndarray],
    seed: int,
    device: str,
) -> MultiOutputRegressor:
    from lightgbm import LGBMRegressor

    device_type = _resolve_lgbm_device(device)
    base = LGBMRegressor(random_state=int(seed), device_type=device_type, **COMPARE_LGBM_RESIDUAL_PARAMS)
    model = MultiOutputRegressor(base)
    fit_kwargs = {}
    if sample_weight is not None:
        fit_kwargs["sample_weight"] = sample_weight
    try:
        model.fit(meta_train, resid_train, **fit_kwargs)
    except Exception as exc:
        if device_type != "cpu":
            warnings.warn(f"LightGBM GPU residual fit failed ({exc}); retrying on CPU.", stacklevel=2)
            base = LGBMRegressor(random_state=int(seed), device_type="cpu", **COMPARE_LGBM_RESIDUAL_PARAMS)
            model = MultiOutputRegressor(base)
            model.fit(meta_train, resid_train, **fit_kwargs)
        else:
            raise
    return model


