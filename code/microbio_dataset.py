def _format_profile_value(value: object) -> str:
    arr = np.asarray(value, dtype=float)
    if arr.ndim == 0:
        return repr(float(arr))
    if arr.ndim == 1:
        return "[" + ", ".join(repr(float(v)) for v in arr) + "]"
    return np.array2string(arr, separator=", ", max_line_width=120)


