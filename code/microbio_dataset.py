def refresh_microbio_generation_summary_provenance(summary_path: str) -> dict:
    """Rewrite provenance fields only. Does not regenerate MICROBIO.csv or change counts."""
    path = os.path.abspath(summary_path)
    if not os.path.isfile(path):
        raise FileNotFoundError(path)
    with open(path, encoding="utf-8") as fh:
        payload = json.load(fh)
    preserved = {key: payload[key] for key in GENERATION_SUMMARY_COUNT_KEYS if key in payload}
    payload.update(microbio_generation_provenance_fields())
    payload.update(preserved)
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(payload, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    return payload


