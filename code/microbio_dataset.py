def repo_relative_path(path: str) -> str:
    """Store dataset provenance as a repo-relative POSIX path, not an absolute Windows path."""
    if not path:
        return path
    normalized = str(path).replace("\\", "/")
    markers = (
        "data/microbio_raw/MICROBIO.csv",
        "data/microbio_formal_dataset/",
        "data/microbio_raw/",
        "results/",
        "data/",
    )
    lower = normalized.lower()
    for marker in markers:
        idx = lower.rfind("/" + marker.lower())
        if idx >= 0:
            return normalized[idx + 1 :]
        idx = lower.find(marker.lower())
        if idx == 0:
            return normalized
        idx = lower.rfind(marker.lower())
        if idx >= 0:
            return normalized[idx:]
    root = os.path.dirname(os.path.abspath(__file__))
    abs_path = os.path.abspath(path)
    try:
        rel = os.path.relpath(abs_path, root)
    except ValueError:
        rel = abs_path
    return rel.replace("\\", "/")


